export const SKILLS: SkillDef[] = (skillsJson as Omit<SkillDef, 'ru'>[]).map((s) => ({
  ...s,
  cls: s.cls as ClassKey,
  ru: RU_BY_ID[s.id] ?? RU_BY_NAME[s.en]
}))

const byId = new Map(SKILLS.map((s) => [s.id, s]))
export const skillDef = (id: number): SkillDef | undefined => byId.get(id)

/** Умения класса в игровом порядке: активные → пассивные → стигмы. */
export function classSkills(cls: ClassKey, type?: SkillType): SkillDef[] {
  const typeOrder: Record<SkillType, number> = { active: 0, passive: 1, stigma: 2 }
  return SKILLS.filter((s) => s.cls === cls && (!type || s.type === type)).sort((a, b) => typeOrder[a.type] - typeOrder[b.type] || a.order - b.order)
}

/** Поиск умения по названию (английскому или русскому) — для импорта гайдов. */
export function findSkillByName(name: string, cls?: ClassKey | null): SkillDef | undefined {
  const n = name.trim().toLowerCase()
  const pool = cls ? SKILLS.filter((s) => s.cls === cls) : SKILLS
  return pool.find((s) => s.en.toLowerCase() === n || s.ru?.toLowerCase() === n)
}

