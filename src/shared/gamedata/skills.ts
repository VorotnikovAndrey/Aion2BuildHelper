// Умения: ID → название, класс, тип (активное / пассивное / стигма), уровень открытия.
// Английские названия — официальные из клиента (через metabot.gg, см. docs/data-sources.md).
// Русские — наш перевод; часть совпадает с тем, как их называют русскоязычные игроки.
// Специализации (варианты 1–5 у активных умений и стигм) — тоже здесь.

import type { ClassKey } from '../types'
import skillsJson from './generated/skills.json'
import specsJson from './generated/specs.json'
import skillsRuJson from './skills-ru.json'

export type SkillType = 'active' | 'passive' | 'stigma'

export interface SkillDef {
  id: number
  slug: string
  en: string
  ru?: string
  cls: ClassKey
  type: SkillType
  /** Уровень персонажа, на котором умение открывается. */
  unlock: number | null
  /** Порядок внутри класса и типа (как в игре). */
  order: number
}

export interface SpecDef {
  /** Номер варианта (1–5). */
  n: number
  /** Минимальный уровень умения. Для пятого варианта стигм — не указан. */
  level: number | null
  en: string
  ru?: string
}

/** Русские названия. Общие умения разных классов (Снятие шока, Попадание шоком…) переведены одинаково. */
const RU_BY_NAME: Record<string, string> = {
  Defiance: 'Снятие шока',
  'Impact Hit': 'Попадание шоком',
  'Survival Willpower': 'Инстинкт выживания',
  'Revitalization Contract': 'Контракт восстановления',
  'Attack Preparation': 'Подготовка к атаке',
  'Armor of Balance': 'Доспехи баланса'
}

/**
 * Русские названия умений всех классов — из русского клиента (база умений Questlog на русском), см. skills-ru.json.
 * Здесь — только поправки поверх: в клиенте два разных умения стража называются «Удар щитом»,
 * у рывка добавляем «(рывок)», чтобы их различать.
 */
const RU_OVERRIDES: Record<number, string> = {
  12430000: 'Удар щитом (рывок)'
}
const RU_BY_ID: Record<string, string> = (skillsRuJson as { names: Record<string, string> }).names

export const SKILLS: SkillDef[] = (skillsJson as Omit<SkillDef, 'ru'>[]).map((s) => ({
  ...s,
  cls: s.cls as ClassKey,
  ru: RU_OVERRIDES[s.id] ?? RU_BY_ID[String(s.id)] ?? RU_BY_NAME[s.en]
}))

const byId = new Map(SKILLS.map((s) => [s.id, s]))
export const skillDef = (id: number): SkillDef | undefined => byId.get(id)

/** Умения класса в игровом порядке: активные → пассивные → стигмы. */
export function classSkills(cls: ClassKey, type?: SkillType): SkillDef[] {
  const typeOrder: Record<SkillType, number> = { active: 0, passive: 1, stigma: 2 }
  return SKILLS.filter((s) => s.cls === cls && (!type || s.type === type)).sort((a, b) => typeOrder[a.type] - typeOrder[b.type] || a.order - b.order)
}

/** Поиск умения по названию (английскому или русскому) — для импорта гайдов. */
export function findSkillByName(name: string, cls?: ClassKey | null): SkillDef | undefined {
  const n = name.trim().toLowerCase()
  const pool = cls ? SKILLS.filter((s) => s.cls === cls) : SKILLS
  return pool.find((s) => s.en.toLowerCase() === n || s.ru?.toLowerCase() === n)
}

